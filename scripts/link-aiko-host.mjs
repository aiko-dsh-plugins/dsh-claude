import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// Development-only overrides resolve the plugin against the actual Aiko Host.
const root = dirname(dirname(fileURLToPath(import.meta.url)))
const host = resolve(process.argv[2] ?? join(root, '../../deepseek-harness'))
const packages = []
for (const group of await readdir(join(host, 'packages'), { withFileTypes: true })) {
  if (!group.isDirectory()) continue
  for (const entry of await readdir(join(host, 'packages', group.name), { withFileTypes: true })) {
    if (entry.isDirectory()) packages.push(join(host, 'packages', group.name, entry.name))
  }
}
for (const entry of await readdir(join(host, 'vendor'), { withFileTypes: true })) {
  if (entry.isDirectory()) packages.push(join(host, 'vendor', entry.name))
}
const overrides = {}
for (const path of packages) {
  let manifest
  try { manifest = JSON.parse(await readFile(join(path, 'package.json'), 'utf8')) }
  catch (error) { if (error.code === 'ENOENT') continue; throw error }
  overrides[manifest.name] = `link:${relative(root, path).replaceAll('\\', '/')}`
}
await writeFile(join(root, 'pnpm-workspace.yaml'), `# Generated by scripts/link-aiko-host.mjs; local paths only.\n${JSON.stringify({ overrides }, null, 2)}\n`)
console.log(`Linked ${Object.keys(overrides).length} package overrides to ${host}`)
